# lowercase לאחסון יעיל
_KEYWORDS_LOWER: list[str] = [kw.lower() for kw in COMPLAINT_KEYWORDS]


def get_complaint_score(text: str) -> int:
    """
    מחזיר ציון — כמה keywords של תלונה נמצאו בטקסט.
    ציון 0 = לא תלונה. ציון 1+ = תלונה.

    :param text: הטקסט לבדיקה (עברית/אנגלית/מעורב)
    :return: int — מספר keywords שנמצאו
    """
    if not text:
        return 0
    text_lower = text.lower()
    return sum(1 for kw in _KEYWORDS_LOWER if kw in text_lower)


def is_complaint(text: str, threshold: int = 1) -> bool:
    """
    האם הטקסט מביע אי-שביעות רצון / מחפש חלופה?

    :param text:      הטקסט לבדיקה
    :param threshold: מינימום keywords לסיווג כתלונה (ברירת מחדל: 1)
    :return: bool
    """
    return get_complaint_score(text) >= threshold


def extract_complaint_keywords(text: str) -> list[str]:
    """
    מחזיר רשימה של keywords שנמצאו בטקסט.
    שימושי ל-logging ו-debugging.

    :param text: הטקסט לבדיקה
    :return: list of matched keywords
    """
    if not text:
        return []
    text_lower = text.lower()
    return [kw for kw in COMPLAINT_KEYWORDS if kw.lower() in text_lower]
